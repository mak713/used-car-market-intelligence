    primary_key,
    listing_id,
    first_seen_at,
    last_seen_at,
    source_file,
    source_file_date,
    {{ j_text('listingType') }}                     as listing_type,
    {{ j_int('year') }}                             as vehicle_year,
    {{ j_text('makeCode') }}                        as make_code,
    {{ j_text('makeName') }}                        as make_name,
    {{ j_text('modelCode') }}                       as model_code,
    {{ j_text('modelName') }}                       as model_name,
    {{ j_text('trim') }}                            as trim,
    {{ j_text('bodyStyle') }}                       as body_style,
    {{ j_int('mileage') }}                          as mileage,
    {{ j_text('dealIndicator') }}                   as deal_indicator,
    {{ j_num('kbbFairPriceLow') }}                  as kbb_fair_price_low,
    {{ j_num('kbbFairPriceHigh') }}                 as kbb_fair_price_high,
    nullif({{ j_bigint('kbbVehicleId') }}, 0)       as kbb_vehicle_id,   -- 0 = absent in the source
    {{ j_text('exteriorColorSimple') }}             as exterior_color,
    {{ j_text('interiorColorSimple') }}             as interior_color,
    {{ j_text('engine') }}                          as engine,
    {{ j_num('displacementUOM') }}                  as displacement_liters,
    {{ j_text('drivetrain') }}                      as drivetrain,
    {{ j_text('transmissionGroup') }}               as transmission_group,
    {{ j_text('fuelTypeGroup') }}                   as fuel_type_group,
    {{ j_int('mpgCity') }}                          as mpg_city,
    {{ j_int('mpgHighway') }}                       as mpg_highway,
    {{ j_num('kbbConsumerRatings') }}               as kbb_consumer_rating,
    {{ j_int('kbbConsumerReviewCount') }}           as kbb_consumer_review_count,
    {{ j_bool('hasLeatherSeats') }}                 as has_leather_seats,
    {{ j_int('daysOnMarket') }}                     as days_on_market,
    {{ j_bool('isHot') }}                           as is_hot,
