    {{ j_bool('isReducedPrice') }}                  as is_reduced_price,
    {{ j_bool('isNoHagglePrice') }}                 as is_no_haggle_price,
    {{ j_bool('hasSpecialOffer') }}                 as has_special_offer,
    {{ j_text('priority') }}                        as priority,
    {{ j_bigint('sellerId') }}                      as seller_id,
    {{ j_int('sellerReviewCount') }}                as seller_review_count,
    {{ j_bool('isPrivateSeller') }}                 as is_private_seller,
    {{ j_text('sellerContractLevel') }}             as seller_contract_level,
    {{ j_int('safetyRecallCount') }}                as safety_recall_count,
    {{ j_int('optionsCount') }}                     as options_count,
    {{ j_int('imagesCount') }}                      as images_count,
    {{ j_text('sellerCity') }}                      as seller_city,
    upper({{ j_text('sellerState') }})              as seller_state,
    {{ j_text('sellerZip') }}                       as seller_zip
